"""Generator for a small, clearly labelled SYNTHETIC textile-like dataset.

These images are procedurally generated woven-looking textures with simple artificial "defects".
They exist only to exercise the software pipeline (tests, demos, smoke runs). They are NOT real
textile images, do NOT represent real defects, and any model trained on them says nothing about
real-world defect recognition. Class names carry a ``synthetic_`` prefix for that reason.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

SYNTHETIC_CLASSES = ("synthetic_normal", "synthetic_blob", "synthetic_stain", "synthetic_line")

README_TEXT = (
    "SYNTHETIC DATA - NOT REAL TEXTILE IMAGES\n"
    "Procedurally generated by textile_defect_detection.synthetic for software testing only.\n"
    "Do not use for model-quality claims. Images with the same group token (g<class><NNN>) share a texture\n"
    "seed and simulate 'specimens' so that group-aware splitting can be exercised.\n"
)


def _texture(rng: np.random.Generator, size: int) -> np.ndarray:
    """Woven-looking base texture (float 0..1, HxW)."""
    y, x = np.mgrid[0:size, 0:size].astype(np.float32)
    period = rng.integers(5, 9)
    phase = rng.uniform(0, 6.28, size=2)
    weave = 0.5 + 0.25 * np.sin(2 * np.pi * x / period + phase[0]) \
        + 0.25 * np.sin(2 * np.pi * y / period + phase[1])
    noise = rng.normal(0, 0.04, size=(size, size)).astype(np.float32)
    return np.clip(0.55 * weave + 0.25 + noise, 0, 1)


def _make_image(label: str, base: np.ndarray, rng: np.random.Generator) -> Image.Image:
    size = base.shape[0]
    # per-image jitter so images of the same "specimen" are similar but never byte-identical
    jitter = rng.normal(0, 0.02, size=base.shape).astype(np.float32)
    base = np.clip(base + jitter, 0, 1)
    rgb = np.stack([base * 0.95, base * 0.85, base * 0.75], axis=-1)
    img = Image.fromarray((np.clip(rgb, 0, 1) * 255).astype(np.uint8), mode="RGB")
    draw = ImageDraw.Draw(img, "RGBA")
    cx, cy = (int(v) for v in rng.integers(size // 4, 3 * size // 4, size=2))
    if label == "synthetic_blob":
        r = int(rng.integers(size // 12, size // 7))
        draw.ellipse([cx - r, cy - r, cx + r, cy + r], fill=(15, 15, 15, 255))
    elif label == "synthetic_stain":
        r = int(rng.integers(size // 7, size // 4))
        draw.ellipse([cx - r, cy - r // 2, cx + r, cy + r // 2], fill=(150, 90, 30, 140))
    elif label == "synthetic_line":
        x0, x1 = sorted(int(v) for v in rng.integers(0, size, size=2))
        draw.line([x0, cy, x1 + size // 3, cy + int(rng.integers(-6, 6))],
                  fill=(20, 20, 20, 255), width=2)
    return img


def generate_synthetic_dataset(out_dir: str | Path, *, images_per_class: int = 24,
                               image_size: int = 96, images_per_group: int = 3,
                               seed: int = 0) -> Path:
    """Write ``<out_dir>/<class>/<class>_g<c><NNN>_<k>.png`` plus ``dataset_info.json``.

    Returns ``out_dir``. Raises FileExistsError if the directory already contains files.
    """
    out = Path(out_dir)
    if out.exists() and any(out.iterdir()):
        raise FileExistsError(f"'{out.name}' already exists and is not empty.")
    out.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(seed)
    for class_index, label in enumerate(SYNTHETIC_CLASSES):
        folder = out / label
        folder.mkdir()
        group_count = -(-images_per_class // images_per_group)  # ceiling division
        written = 0
        for g in range(group_count):
            base = _texture(np.random.default_rng(int(rng.integers(0, 2**31))), image_size)
            for k in range(images_per_group):
                if written >= images_per_class:
                    break
                img = _make_image(label, base, rng)
                # group token is unique across classes: g<class_index><group number>
                img.save(folder / f"{label}_g{class_index}{g:03d}_{k}.png")
                written += 1
    info = {
        "dataset_id": "synthetic-demo",
        "dataset_name": "SYNTHETIC demo dataset (generated, not real textiles)",
        "source_url": "generated locally by textile_defect_detection.synthetic",
        "publisher": "this repository",
        "version": f"seed-{seed}",
        "download_date": "n/a",
        "license": "generated data, no third-party content",
        "citation": "n/a",
        "usage_restrictions": "software testing only; not evidence of real-world performance",
        "annotation_format": "image-level class label (folder name)",
        "synthetic": True,
        "preparation_steps": ["procedural generation"],
        "notes": "SYNTHETIC. Group id is the 'g<digits>' token in the file name (regex _(g\\d+)_).",
    }
    (out / "dataset_info.json").write_text(json.dumps(info, indent=2) + "\n", encoding="utf-8")
    (out / "README_SYNTHETIC.txt").write_text(README_TEXT, encoding="utf-8")
    return out
